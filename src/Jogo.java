public class Jogo {

    String nome;
    double nota;
    String lancamento;
    String generos;
    String plataformas;
    String imagem;

    public Jogo(String nome, double nota, String lancamento,
                String generos, String plataformas, String imagem) {

        this.nome = nome;
        this.nota = nota;
        this.lancamento = lancamento;
        this.generos = generos;
        this.plataformas = plataformas;
        this.imagem = imagem;
    }
}